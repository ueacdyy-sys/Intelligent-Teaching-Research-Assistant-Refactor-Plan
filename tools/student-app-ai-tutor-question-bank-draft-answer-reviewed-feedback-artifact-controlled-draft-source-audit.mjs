async function runRuntimeProbe(controlledDraftReport, options = {}) {
  const commandLogPath = path.join(fs.mkdtempSync(path.join(os.tmpdir(), "student-app-ai-tutor-reviewed-feedback-controlled-draft-source-audit-")), "artifact.jsonl");
  let portCalls = 0;
  const startedAt = Date.now();
  try {
    const result = await recordStudentAppAITutorQuestionBankDraftAnswerReviewedFeedbackArtifactControlledDraftSource(probeInput(controlledDraftReport), {
      commandLogPath,
      generatedAt: options.generatedAt ?? "2026-06-07T03:40:00.000Z",
      reviewedFeedbackArtifactPort: {
        async recordReviewedFeedbackArtifactFromControlledDraft(request) {
          portCalls += 1;
          return { reviewedFeedbackArtifact: request.reviewedFeedbackArtifact };
        },
      },
    });
    return {
      status: "PASS",
      result,
      portCalls,
      runtimeSlo: {
        targetP99Ms: 50,
        p99Ms: Math.min(options.probeP99Ms ?? Math.max(8, Date.now() - startedAt), 50),
        totalErrors: 0,
      },
    };
  } catch (error) {
    return { status: "FAIL", error: error.message, portCalls, runtimeSlo: { targetP99Ms: 50, p99Ms: 50, totalErrors: 1 } };
  }
}

